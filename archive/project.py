"""## 3. Features (causal, trailing windows)"""

"""Causal feature construction.

Prediction contract (what one row represents):
    One row = one room at one grid timestamp ``t``. The model estimates the number
    of people present at ``t`` using ONLY environmental measurements observed at or
    before ``t``. Occupancy-derived signals (``cfg.exclude_cols``) and lagged
    occupancy are never used (target leakage, Week 5.6).
"""

from dataclasses import dataclass
from typing import Dict, List

import numpy as np
import pandas as pd



@dataclass
class FeatureSet:
    """Container returned by :func:`build_features`.

    Attributes:
        X: Feature matrix (may contain NaN; imputation happens inside the model
            pipeline so it is fit on training data only).
        y: Target (people count).
        meta: ``timestamp`` and ``room`` for each row.
        groups: Feature-group name -> list of column names (for ablation).
    """

    X: pd.DataFrame
    y: pd.Series
    meta: pd.DataFrame
    groups: Dict[str, List[str]]


def build_features(df: pd.DataFrame, cfg: Config) -> FeatureSet:
    """Build trailing-window (causal) features from a clean regular-grid frame.

    Feature groups:
        * ``raw``: the current reading of each environmental sensor.
        * ``rolling``: trailing mean and standard deviation over each window.
        * ``trend``: change over each window, ``x(t) - x(t - w)`` (e.g. CO2 rise rate).
        * ``time``: sine/cosine time-of-day and weekend flag (optional).

    Args:
        df: Output of :func:`occupancy.io.clean`.
        cfg: Workflow configuration.

    Returns:
        A :class:`FeatureSet`.

    Raises:
        ValueError: If an excluded column is also listed as an input, or if a
            window is shorter than one grid step.
    """
    leak = set(cfg.exclude_cols) & set(cfg.env_cols)
    if leak:
        raise ValueError(f"Occupancy-derived columns used as inputs (leakage): {sorted(leak)}")
    step = cfg.step_minutes
    steps = []
    for w in cfg.windows_min:
        n = int(round(w / step))
        if n < 1:
            raise ValueError(f"Window {w} min is shorter than the {step} min grid step.")
        steps.append((w, n))

    d = df.sort_values(["room", "timestamp"]).reset_index(drop=True)
    feats: Dict[str, pd.Series] = {}
    groups: Dict[str, List[str]] = {"raw": [], "rolling": [], "trend": [], "time": []}
    g = d.groupby("room", sort=False)
    for c in cfg.env_cols:
        feats[c] = d[c]
        groups["raw"].append(c)
        for w, n in steps:
            roll = g[c].transform(lambda s, n=n: s.rolling(n, min_periods=1).mean())
            diff = d[c] - g[c].shift(n)
            items = [(f"{c}_mean{w}m", roll, "rolling"), (f"{c}_chg{w}m", diff, "trend")]
            if n >= 2:  # a standard deviation needs at least two samples in the window
                std = g[c].transform(lambda s, n=n: s.rolling(n, min_periods=2).std())
                items.append((f"{c}_std{w}m", std, "rolling"))
            for name, ser, grp in items:
                feats[name] = ser
                groups[grp].append(name)

    if cfg.use_time_features:
        hour = d["timestamp"].dt.hour + d["timestamp"].dt.minute / 60.0
        feats["hour_sin"] = np.sin(2 * np.pi * hour / 24.0)
        feats["hour_cos"] = np.cos(2 * np.pi * hour / 24.0)
        feats["is_weekend"] = (d["timestamp"].dt.dayofweek >= 5).astype(float)
        groups["time"] = ["hour_sin", "hour_cos", "is_weekend"]

    unknown = set(cfg.feature_groups) - {"raw", "rolling", "trend", "time"}
    if unknown:
        raise ValueError(f"Unknown feature groups: {sorted(unknown)}")
    drop = [c for g, cols in groups.items() if g not in cfg.feature_groups for c in cols]
    groups = {g: cols for g, cols in groups.items() if g in cfg.feature_groups}
    if not groups:
        raise ValueError("No feature groups selected.")
    X = pd.DataFrame(feats).drop(columns=drop)
    meta = d[["timestamp", "room"]].copy()
    y = d[cfg.target_col].astype(float)
    groups = {k: v for k, v in groups.items() if v}
    return FeatureSet(X=X, y=y, meta=meta, groups=groups)

"""## 4. Models and baselines"""

"""Baselines and candidate regression models (all taught in Week 5).

Every model is an sklearn ``Pipeline`` whose final step is named ``model`` and whose
imputer/scaler steps are fit on the training data only (no preprocessing leakage).
"""

from typing import Dict, List

import numpy as np
import pandas as pd
from sklearn.base import BaseEstimator, RegressorMixin
from sklearn.compose import ColumnTransformer
from sklearn.dummy import DummyRegressor
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LinearRegression, Ridge
from sklearn.neural_network import MLPRegressor
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVR
from sklearn.tree import DecisionTreeRegressor


TIME_COLS = ["hour_sin", "hour_cos", "is_weekend"]


class ScheduleBaseline(BaseEstimator, RegressorMixin):
    """Mean occupancy by (weekday/weekend, 15-minute time-of-day slot).

    Uses time of week only, no sensor data. A sensor-based model has to beat this
    to show that the environmental readings add information beyond the timetable.
    Expects the three columns in ``TIME_COLS`` (hour_sin, hour_cos, is_weekend).
    """

    @staticmethod
    def _key(X: np.ndarray) -> np.ndarray:
        angle = np.arctan2(X[:, 0], X[:, 1]) % (2 * np.pi)
        slot = np.round(angle / (2 * np.pi) * 96).astype(int) % 96
        return (X[:, 2] > 0.5).astype(int) * 100 + slot

    def fit(self, X, y):
        X, y = np.asarray(X, float), np.asarray(y, float)
        self.table_ = pd.Series(y).groupby(self._key(X)).mean().to_dict()
        self.mean_ = float(y.mean())
        self.n_features_in_ = X.shape[1]
        return self

    def predict(self, X):
        keys = self._key(np.asarray(X, float))
        return np.array([self.table_.get(int(k), self.mean_) for k in keys])


def _prep(scale: bool) -> List[tuple]:
    steps = [("impute", SimpleImputer(strategy="median"))]
    if scale:
        steps.append(("scale", StandardScaler()))
    return steps


def make_models(cfg_seed: int = 42, baseline_col: str = "co2",
                include_schedule: bool = False) -> Dict[str, Pipeline]:
    """Create the baselines and candidate models.

    Args:
        cfg_seed: Random seed for stochastic models.
        baseline_col: Single raw sensor column for the simple physical baseline.
        include_schedule: Add the time-of-week-only ``baseline_schedule`` (needs the
            time features).

    Returns:
        Ordered dict name -> unfitted Pipeline. Names starting with ``baseline_``
        are reference models, not selection candidates.
    """
    models = {
        "baseline_mean": Pipeline(
            _prep(False) + [("model", DummyRegressor(strategy="mean"))]
        ),
        "baseline_co2_linear": Pipeline(
            [("select", ColumnTransformer([("c", "passthrough", [baseline_col])])),
             *_prep(False), ("model", LinearRegression())]
        ),
        "linear": Pipeline(_prep(True) + [("model", Ridge(alpha=1.0))]),
        "tree": Pipeline(
            _prep(False)
            + [("model", DecisionTreeRegressor(max_depth=8, min_samples_leaf=20,
                                               random_state=cfg_seed))]
        ),
        "svr": Pipeline(_prep(True) + [("model", SVR(kernel="rbf", C=10.0, epsilon=0.5))]),
        "nn": Pipeline(
            _prep(True)
            + [("model", MLPRegressor(hidden_layer_sizes=(32, 16), early_stopping=True,
                                      max_iter=800, random_state=cfg_seed))]
        ),
    }
    if include_schedule:
        sched = Pipeline([
            ("select", ColumnTransformer([("t", "passthrough", TIME_COLS)])),
            ("model", ScheduleBaseline()),
        ])
        out = {"baseline_mean": models.pop("baseline_mean"), "baseline_schedule": sched}
        out.update(models)
        return out
    return models


