"""End-to-end workflow: audit -> clean -> features -> select -> final test -> studies.

Usage::

    python -m occupancy.pipeline --config config.json --out results
    python -m occupancy.pipeline --synthetic --out results_synthetic

The held-out test period is scored exactly once, after model selection.
"""

import argparse
